const dicts: Record<Lang, Dict> = { en, ru, zh };

export const LANGUAGES: { code: Lang; label: string }[] = [
  { code: "en", label: "English" },
  { code: "ru", label: "Русский" },
  { code: "zh", label: "中文" },
];

interface I18nState {
  lang: Lang;
  setLang: (l: Lang) => void;
  t: (key: TKey) => string;
}

const I18nContext = React.createContext<I18nState | null>(null);

export function useI18n(): I18nState {
  const ctx = React.useContext(I18nContext);
  if (!ctx) throw new Error("useI18n must be used within I18nProvider");
  return ctx;
}

export function I18nProvider({ children }: { children: React.ReactNode }) {
  const [lang, setLangState] = React.useState<Lang>(
    () => (localStorage.getItem("sr_lang") as Lang) || "en",
  );

  const setLang = React.useCallback((l: Lang) => {
    localStorage.setItem("sr_lang", l);
    setLangState(l);
  }, []);

  const t = React.useCallback((key: TKey) => dicts[lang][key] || en[key] || String(key), [lang]);

  return <I18nContext.Provider value={{ lang, setLang, t }}>{children}</I18nContext.Provider>;
}
